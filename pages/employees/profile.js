    pdf.setFontSize(14);
    pdf.setFont("helvetica", "normal");
    pdf.text("Employee Bio Data", 105, 42, { align: "center" });

    // Employee Details
    pdf.setFontSize(10);
    pdf.setFont("helvetica", "bold");
    pdf.text("PERSONAL INFORMATION", 15, 55);
    
